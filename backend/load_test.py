"""
LOAD TEST — concurrent scoring latency (p50 / p95 / p99)
--------------------------------------------------------
Measures the latency of the scoring service under concurrent load and reports
percentiles + throughput. Two modes:

  * in-process (default) : calls ``FraudDetector.investigate_event`` directly
    (no network) using a thread pool, so the pipeline's own cost dominates.
  * --url <base>         : drives a running server over HTTP (real end-to-end),
    e.g. ``python load_test.py --url http://127.0.0.1:8100``.

Usage (from backend/):

    python load_test.py --n 300 --concurrency 8 --warmup 20
    python load_test.py --url http://127.0.0.1:8100 --n 200 --concurrency 10

Writes a report to ../docs/PERFORMANCE.md and prints a summary.
"""

from __future__ import annotations

import argparse
import json
import os
import statistics
import time
from concurrent.futures import ThreadPoolExecutor

from app.data_generator import generate_events


def _build_event_pool(n_events: int, seed: int = 99) -> list[dict]:
    """A realistic mix of clean / fraud / borderline payments to score."""
    df = generate_events(n_bona_fide=max(1, n_events), n_fraud=max(1, n_events // 6),
                         seed=seed, n_reviewish=max(1, n_events // 10))
    cols = ["user_id", "device_id", "card_last4", "amount_inr", "merchant",
            "payment_method", "billing_zip", "shipping_zip", "attempt_count",
            "is_new_device", "is_international", "ip_geo_match", "typing_seconds",
            "three_ds_passed", "status"]
    events = []
    for _, row in df.iterrows():
        ev = {c: row[c] for c in cols if c in df.columns}
        for k in ("amount_inr", "typing_seconds"):
            if k in ev:
                ev[k] = float(ev[k])
        for k in ("attempt_count",):
            if k in ev:
                ev[k] = int(ev[k])
        events.append(ev)
    return events


def _percentiles(samples: list[float]) -> dict:
    s = sorted(samples)
    n = len(s)

    def pct(p: float) -> float:
        if n == 0:
            return 0.0
        idx = min(n - 1, max(0, int(round(p / 100.0 * n + 0.5)) - 1))
        return s[idx]

    return {
        "min": round(s[0], 2) if n else 0.0,
        "mean": round(statistics.fmean(s), 2) if n else 0.0,
        "median": round(statistics.median(s), 2) if n else 0.0,
        "p50": round(pct(50), 2),
        "p90": round(pct(90), 2),
        "p95": round(pct(95), 2),
        "p99": round(pct(99), 2),
        "max": round(s[-1], 2) if n else 0.0,
    }


def _run_inprocess(pool: list[dict], n: int, concurrency: int, warmup: int) -> list[float]:
    from app.pipeline import FraudDetector
    det = FraudDetector.load()

    def one(i: int) -> float:
        ev = dict(pool[i % len(pool)])
        ev["event_id"] = f"load_{i}"
        t0 = time.perf_counter()
        det.investigate_event(ev)
        return (time.perf_counter() - t0) * 1000.0

    for i in range(warmup):
        one(-i - 1)
    samples: list[float] = []
    with ThreadPoolExecutor(max_workers=concurrency) as ex:
        for ms in ex.map(one, range(n)):
            samples.append(ms)
    return samples


def _run_http(url: str, pool: list[dict], n: int, concurrency: int, warmup: int,
              token: str | None) -> list[float]:
    import httpx
    url = url.rstrip("/")
    headers = {"Authorization": f"Bearer {token}"} if token else {}

    def one(i: int) -> float:
        ev = dict(pool[i % len(pool)])
        ev["event_id"] = f"load_{i}"
        t0 = time.perf_counter()
        r = httpx.post(f"{url}/api/investigate", json={"event": ev},
                       headers=headers, timeout=30.0)
        r.raise_for_status()
        return (time.perf_counter() - t0) * 1000.0

    for i in range(warmup):
        one(-i - 1)
    samples: list[float] = []
    with ThreadPoolExecutor(max_workers=concurrency) as ex:
        for ms in ex.map(one, range(n)):
            samples.append(ms)
    return samples


def _write_report(mode: str, n: int, concurrency: int, stats: dict,
                  wall_s: float, out_dir: str) -> str:
    rps = round(n / wall_s, 2) if wall_s > 0 else 0.0
    path = os.path.join(out_dir, "PERFORMANCE.md")
    lines = [
        "# Sentinel AI — Load Test Results",
        "",
        "> Generated by `backend/load_test.py`. Latency is per scoring request in ms.",
        "",
        f"- **Mode:** {mode}",
        f"- **Requests:** {n}",
        f"- **Concurrency:** {concurrency}",
        f"- **Wall time:** {wall_s:.2f} s",
        f"- **Throughput:** {rps} req/s",
        "",
        "| metric | latency (ms) |",
        "| --- | --- |",
    ]
    for k in ("min", "mean", "median", "p50", "p90", "p95", "p99", "max"):
        lines.append(f"| {k} | {stats[k]} |")
    lines.append("")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    return path


def main() -> None:
    ap = argparse.ArgumentParser(description="Sentinel AI scoring load test")
    ap.add_argument("--url", default=None, help="base URL; omit for in-process mode")
    ap.add_argument("--n", type=int, default=300, help="number of requests")
    ap.add_argument("--concurrency", type=int, default=8, help="worker threads")
    ap.add_argument("--warmup", type=int, default=20, help="warm-up requests")
    ap.add_argument("--token", default=None, help="bearer token for --url mode")
    ap.add_argument("--no-write", action="store_true", help="do not write the report")
    args = ap.parse_args()

    pool = _build_event_pool(n_events=max(50, args.n))
    print(f"event pool: {len(pool)} | requests: {args.n} | concurrency: {args.concurrency}")

    t0 = time.perf_counter()
    if args.url:
        samples = _run_http(args.url, pool, args.n, args.concurrency, args.warmup, args.token)
        mode = f"http ({args.url})"
    else:
        samples = _run_inprocess(pool, args.n, args.concurrency, args.warmup)
        mode = "in-process"
    wall = time.perf_counter() - t0

    stats = _percentiles(samples)
    rps = round(len(samples) / wall, 2) if wall > 0 else 0.0
    result = {"mode": mode, "n": args.n, "concurrency": args.concurrency,
              "wall_s": round(wall, 2), "throughput_rps": rps, **stats}
    print(json.dumps(result, indent=2))

    if not args.no_write:
        out_dir = os.path.join(os.path.dirname(__file__), "..", "docs")
        os.makedirs(out_dir, exist_ok=True)
        path = _write_report(mode, len(samples), args.concurrency, stats, wall, out_dir)
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
